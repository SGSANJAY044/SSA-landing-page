/** Look up a UI string, falling back to English. */
export function t(locale, key) {
  return strings[locale]?.[key] ?? strings[defaultLocale][key] ?? key;
}

/** Pick the locale's value from a `{ en, ta }` content object. */
export function pick(locale, value) {
  if (value == null || typeof value !== 'object' || Array.isArray(value)) return value;
  return value[locale] ?? value[defaultLocale];
}

// Deploy base (e.g. `/SSA-landing-page` on GitHub Pages) without a trailing slash; '' at the domain root.
const BASE = import.meta.env.BASE_URL.replace(/\/$/, '');

/** Prefix a public file or site path with the deploy base (`/logo.webp` → `/SSA-landing-page/logo.webp`). */
export function asset(path) {
  return `${BASE}${path.startsWith('/') ? path : `/${path}`}`;
}

/** Prefix a site path with the deploy base and locale segment (`/services/x/` → `/ta/services/x/`). */
export function localePath(locale, path = '/') {
  const clean = path.startsWith('/') ? path : `/${path}`;
  return asset(locale === defaultLocale ? clean : `/${locale}${clean}`);
}

/** Strip the deploy base and any locale prefix from a pathname. */
export function basePath(pathname) {
  const local = BASE && pathname.startsWith(BASE) ? pathname.slice(BASE.length) : pathname;
  const stripped = local.replace(/^\/(ta)(?=\/|$)/, '');
  return stripped || '/';
}

export function otherLocale(locale) {
  return locale === 'ta' ? 'en' : 'ta';
}
